#!/usr/bin/env bash
# bash-encrypter.sh - wrap a bash script so it asks for a passphrase before running
#
# Flag mode:        ./bash-encrypter.sh SOURCE_FILE -p PASSPHRASE
# Interactive mode: ./bash-encrypter.sh
#
# Output is written next to the source as NAME-encrypted.EXT

set -euo pipefail

usage() {
  cat <<EOF
Usage:
  $0 SOURCE_FILE -p PASSPHRASE    flag mode
  $0 [SOURCE_FILE]                interactive mode (prompts for what is missing)
EOF
}

die() {
  echo "error: $*" >&2
  exit 1
}

# Build the output path: /dir/name.sh -> /dir/name-encrypted.sh
out_path() {
  local src=$1 dir base
  dir=$(dirname -- "$src")
  base=$(basename -- "$src")
  if [[ $base == *.* && $base != .* ]]; then
    printf '%s/%s-encrypted.%s\n' "$dir" "${base%.*}" "${base##*.}"
  else
    printf '%s/%s-encrypted\n' "$dir" "$base"
  fi
}

# Write a self-decrypting script that embeds the encrypted source
build_encrypted() {
  local src=$1 pass=$2 out=$3 payload salt

  # 8 random bytes from /dev/urandom, as hex for openssl -S
  salt=$(head -c 8 /dev/urandom | od -An -tx1 | tr -d ' \n') || die "could not read /dev/urandom"

  # The marker line lets the stub detect a wrong passphrase reliably
  payload=$({ printf '#BASHENC-OK\n'; cat -- "$src"; } |
    BASHENC_PASS="$pass" openssl enc -aes-256-cbc -pbkdf2 -iter 600000 -S "$salt" -a -A \
      -pass env:BASHENC_PASS) || die "encryption failed"

  {
    printf '#!/usr/bin/env bash\n'
    printf '# Passphrase-protected script generated by bash-encrypter.sh\n'
    printf "ENC_SALT='%s'\n" "$salt"
    printf "ENC_PAYLOAD='%s'\n" "$payload"
    cat <<'STUB'

ENC_ARGS=()
ENC_PASS=""
ENC_SAVE=0
ENC_SAVE_PATH=""

while [[ $# -gt 0 ]]; do
  case $1 in
    -p)
      [[ $# -ge 2 ]] || { echo "error: -p needs a passphrase" >&2; exit 1; }
      ENC_PASS=$2
      shift 2
      ;;
    --save-decrypted)
      ENC_SAVE=1
      shift
      ;;
    --save-decrypted=*)
      ENC_SAVE=1
      ENC_SAVE_PATH=${1#*=}
      shift
      ;;
    *)
      ENC_ARGS+=("$1")
      shift
      ;;
  esac
done

if [[ -z $ENC_PASS ]]; then
  read -rsp "$(basename -- "$0") Is Encrypted - Enter Passphrase: " ENC_PASS
  echo
fi

ENC_SRC=$(printf '%s' "$ENC_PAYLOAD" |
  BASHENC_PASS="$ENC_PASS" openssl enc -d -aes-256-cbc -pbkdf2 -iter 600000 -a -A \
    -S "$ENC_SALT" -pass env:BASHENC_PASS 2>/dev/null) || ENC_SRC=""

if [[ ${ENC_SRC%%$'\n'*} != "#BASHENC-OK" ]]; then
  echo "error: wrong passphrase" >&2
  exit 1
fi

if (( ENC_SAVE )); then
  [[ -n $ENC_SAVE_PATH ]] || ENC_SAVE_PATH="$(dirname -- "$0")/decrypted-$(basename -- "$0")"
  if [[ -e $ENC_SAVE_PATH ]]; then
    echo "error: $ENC_SAVE_PATH already exists" >&2
    exit 1
  fi
fi

# Feed the source through a pipe on fd 3 instead of argv, so the plaintext
# never appears in /proc/PID/cmdline (world-readable) and is not limited by
# MAX_ARG_STRLEN (128 KiB). Sourcing keeps $0 and the arguments intact.
# The marker line is stripped so $LINENO matches the original script.
bash -c '. /dev/fd/3' "$0" "${ENC_ARGS[@]}" 3< <(printf '%s\n' "${ENC_SRC#*$'\n'}")
ENC_RC=$?

if (( ENC_SAVE )); then
  (
    umask 077
    printf '%s\n' "${ENC_SRC#*$'\n'}" > "$ENC_SAVE_PATH"
  )
  echo "decrypted script saved to $ENC_SAVE_PATH" >&2
fi

exit $ENC_RC
STUB
  } > "$out"

  chmod +x -- "$out"
}

src=""
pass=""
have_pass=0

while [[ $# -gt 0 ]]; do
  case $1 in
    -p)
      [[ $# -ge 2 ]] || die "-p needs a passphrase"
      pass=$2
      have_pass=1
      shift 2
      ;;
    -h|--help)
      usage
      exit 0
      ;;
    -*)
      die "unknown option: $1"
      ;;
    *)
      [[ -z $src ]] || die "only one source file can be given"
      src=$1
      shift
      ;;
  esac
done

if [[ -z $src ]]; then
  read -rp "> enter source file: " src
fi

[[ -f $src && -r $src ]] || die "cannot read source file: $src"

if (( ! have_pass )); then
  read -rsp "> enter passphrase: " pass
  echo
  read -rsp "> passphrase confirm: " confirm
  echo
  [[ $pass == "$confirm" ]] || die "passphrases do not match"
fi

[[ -n $pass ]] || die "passphrase cannot be empty"

out=$(out_path "$src")

echo "encrypting $src..."
build_encrypted "$src" "$pass" "$out"
echo "> $out"
